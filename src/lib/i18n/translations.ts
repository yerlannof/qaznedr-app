export type SupportedLocale = keyof typeof translations;
export type TranslationKeys = typeof translations.ru;

export function translate(
  locale: string,
  key: string,
  params?: Record<string, unknown>
): string {
  const currentTranslations =
    (translations as Record<string, unknown>)[locale] || translations.ru;
  const keys = key.split('.');
  let current: unknown = currentTranslations;

  for (const keyPart of keys) {
    if (current && typeof current === 'object' && keyPart in current) {
      current = (current as Record<string, unknown>)[keyPart];
    } else {
      // Fallback to Russian if key not found
      let fallback: unknown = translations.ru;
      for (const fbPart of keys) {
        if (fallback && typeof fallback === 'object' && fbPart in fallback) {
          fallback = (fallback as Record<string, unknown>)[fbPart];
        } else {
          return key; // Return key itself if not found
        }
      }
      current = fallback;
      break;
    }
  }

  let result = typeof current === 'string' ? current : key;

  if (params && typeof result === 'string') {
    Object.entries(params).forEach(([paramKey, value]) => {
      result = result.replace(
        new RegExp(`\\{${paramKey}\\}`, 'g'),
        String(value)
      );
    });
  }

  return result;
}

